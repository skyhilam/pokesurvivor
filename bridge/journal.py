    def evidence(self, q: dict[str, Any], rec: dict[str, Any]) -> list[str]:
        about, kind, lines = q["about"], q["kind"], []
        t, lv, kills = float(rec.get("time") or 0), rec.get("level"), rec.get("kills", 0)
        if kind == "object":
            hits = [o for o in rec.get("opportunities") or [] if o.get("type") == about]
            for h in hits[:3]:
                lines.append(f"reached it ({h.get('why')}): changes {h.get('reward')}, HP cost {h.get('hp_cost')}")
            if not hits:
                lines.append("I did not reach it this run")
            if self.world:
                lines.append("all-time: " + self.world.object_line(about))
        elif kind == "pickup":
            obs = ((rec.get("world_deltas") or {}).get("pickups") or {}).get(about)
            if obs and obs.get("n"):
                avg = {k: round(v / obs["n"], 3) for k, v in (obs.get("sum") or {}).items() if abs(v) > 1e-6}
                lines.append(f"collected it {obs['n']}x this run, average change {avg}")
            else:
                lines.append("I did not collect it this run")
        elif kind in ("boss", "cause"):
            key = about.split(":", 1)[1] if kind == "cause" else about
            ds = rec.get("damage_sources") or {}
            share = float(ds.get(key, 0)) / (sum(float(v) for v in ds.values()) or 1)
            lines.append(f"this run it caused {share:.0%} of the damage I took; the run ended by {rec.get('death_cause')}")
            table = self.data.get("cause_stance", {}).get(key) or {}
            for s, (n, ssum) in sorted(table.items(), key=lambda kv: kv[1][1] / max(1, kv[1][0])):
                lines.append(f"playing {STANCES.get(s, {}).get('label', s)}: on average {ssum / max(1, n):.0%} of my damage over {n} runs")
            if kind == "boss":
                lines.append(f"bosses I defeated this run: {rec.get('bosses_defeated') or rec.get('boss_kills', 0)}")
        elif kind == "partner":
            target = self._partner_name(about.split(":", 1)[1]) or about
            name = rec.get("partner")
            if name == target:
                others = [r["time"] for r in self.engine.kb.get("runs", []) if r.get("partner") != name]
                avg = f"{_mmss(sum(others) / len(others))}" if others else "n/a"
                lines.append(f"played {name}: survived {_mmss(t)}, Lv{lv}, {kills} kills (my average with other partners {avg})")
            else:
                lines.append(f"I played {name}, not {target}")
        elif kind == "meta":
            ms = self.data["meta_seen"]
            lines.append(f"gacha pulls so far: {ms.get('gacha_pulls', 0)}; partners gained: {[p.get('name') for p in ms.get('partners_gained', [])]}")
        elif kind == "card":
            for b in self.data["beliefs"].values():
                if b["about"] == about:
                    lines.append(f"[{b['status']}] {b['claim']}")
        elif kind == "message":
            lines += self._message_effect(q, rec)
        return lines[:6]

    @staticmethod
    def _message_effect(q: dict[str, Any], rec: dict[str, Any]) -> list[str]:
        """What changed in the 30 s after I read the message, compared with the 30 s before?"""
        norm = q["about"][4:]
        hits = [m for m in rec.get("messages") or [] if isinstance(m, dict)
                and re.sub(r"\d+", "#", str(m.get("text", "")).lower())[:80] == norm]
        if not hits:
            return ["the message did not appear this run"]
        t0 = float(hits[0].get("t") or 0)
        tl = rec.get("timeline") or []

        def window(a: float, b: float) -> tuple[float, int]:
            pts = [p for p in tl if a < float(p.get("t", 0)) <= b]
            dmg = sum(float(p.get("dmg_pct_maxhp") or 0) for p in pts)
            k = (pts[-1].get("kills", 0) - pts[0].get("kills", 0)) if len(pts) >= 2 else 0
            return dmg, k
        before, after = window(t0 - 30, t0), window(t0, t0 + 30)
        return [f"it appeared at {_mmss(t0)}",
                f"30s before: took {before[0]:.0%} max HP, killed {before[1]} | 30s after: took {after[0]:.0%} max HP, killed {after[1]}"]

    def _update_cause_stance(self, rec: dict[str, Any], stance: Optional[str]) -> None:
        """Per damage source: what share of my damage it caused under each play style (to compare styles)."""
        if not stance:
            return
        ds = rec.get("damage_sources") or {}
        tot = sum(float(v) for v in ds.values())
        if tot <= 0:
            return
        cs = self.data.setdefault("cause_stance", {})
        for k, v in ds.items():
            row = cs.setdefault(k, {}).setdefault(stance, [0, 0.0])
            row[0] += 1
            row[1] = round(row[1] + float(v) / tot, 4)

