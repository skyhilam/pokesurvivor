#!/usr/bin/env python3
"""
Player Journal - the bot's notebook (pure observation, no game-source knowledge)
================================================================================
A player does not tune "fear +35%". A player asks questions, forms hunches,
tests them and remembers what they found out. This module keeps that notebook:

- questions : things I want to find out ("what does the purple portal do?")
- beliefs   : things I think are true, with evidence for/against
- diary     : one entry per run (plan -> what happened -> what I learned)
- next_plan : the plan for the next run (question to answer, partner, build, stance)

Questions are generated by code ONLY from what the bot itself observed
(first sightings, surprises, untried options, repeated deaths). Jev (choice-only
API) picks which question to chase, judges evidence and plans the next run.
"""

