MAX_OPEN_QUESTIONS = 30
NOVEL_PREFIXES = ("object:", "pickup:", "boss:")


def _mmss(sec: float) -> str:
    sec = max(0, int(sec))
    return f"{sec // 60:02d}:{sec % 60:02d}"


def _pretty(key: str) -> str:
    return key.split(":", 1)[-1].replace("-", " ") if key else "?"


_BRIDGE_BUILD: Optional[str] = None


def bridge_build() -> str:
    """Short hash of the live bridge sources; stamped into every plan so each
    run record says which code produced it."""
    global _BRIDGE_BUILD
    if _BRIDGE_BUILD is None:
        h = hashlib.sha1()
        for p in sorted(Path(__file__).resolve().parent.glob("*.py")):
            if p.name.startswith(("test_", "cleanup_")):
                continue
            try:
                h.update(p.read_bytes())
            except OSError:
                pass
        _BRIDGE_BUILD = h.hexdigest()[:8]
    return _BRIDGE_BUILD


def default_journal() -> dict[str, Any]:
    return {"version": 1, "beliefs": {}, "questions": {}, "diary": [], "next_plan": None,
            "seq": {"b": 0, "q": 0}, "seeded": False, "seen_messages": [], "stance_stats": {},
            "topic_stats": {}, "topic_stats_v1": False,
            "meta_seen": {"owned": [], "tickets": {}, "gacha_pulls": 0, "save_streak": 0, "partners_gained": []}}


class Journal:
    def __init__(self, log_dir: Path, engine: Any, world: Any = None) -> None:
        self.path = Path(log_dir) / "journal.json"
        self.md_path = Path(log_dir) / "JOURNAL.md"
        self.engine = engine
        self.world = world
        self.data = self._load()

    # ------------------------------------------------------------------ persistence
    def _load(self) -> dict[str, Any]:
        d = default_journal()
        if self.path.is_file():
            try:
                raw = json.loads(self.path.read_text(encoding="utf-8"))
                d.update(raw)
                for k, v in default_journal()["meta_seen"].items():
                    d["meta_seen"].setdefault(k, v)
            except Exception as e:
                print(f"[Journal] load failed: {e}")
        return d

    def save(self) -> None:
        tmp = self.path.with_suffix(".tmp")
        tmp.write_text(json.dumps(self.data, indent=1, ensure_ascii=False), encoding="utf-8")
        tmp.replace(self.path)

    # ------------------------------------------------------------------ primitives
    def _next_id(self, kind: str) -> str:
        self.data["seq"][kind] = self.data["seq"].get(kind, 0) + 1
        return f"{kind}{self.data['seq'][kind]}"

    def has_topic(self, about: str) -> bool:
        return any(q["about"] == about for q in self.data["questions"].values()) or \
            any(b["about"] == about for b in self.data["beliefs"].values())

    def add_question(self, ask: str, about: str, kind: str, priority: float, origin: str = "",
                     candidates: Optional[list[str]] = None) -> Optional[str]:
        if any(q["about"] == about and q["status"] != "answered" for q in self.data["questions"].values()):
            return None
        if any(q["about"] == about for q in self.data["questions"].values()) and kind not in ("cause",):
            return None
        qid = self._next_id("q")
        self.data["questions"][qid] = {"ask": ask, "about": about, "kind": kind, "status": "open",
                                       "priority": round(priority, 2), "times_focused": 0, "origin": origin,
                                       "candidates": candidates or [], "created": time.time(), "answer": None}
        self._trim_questions()
        return qid

    def _trim_questions(self) -> None:
        focus = (self.data.get("next_plan") or {}).get("focus_question")
        open_q = [(k, q) for k, q in self.data["questions"].items()
                  if q["status"] == "open" and k != focus]
        n_open = sum(1 for q in self.data["questions"].values() if q["status"] != "answered")
        if n_open > MAX_OPEN_QUESTIONS:
            open_q.sort(key=lambda kq: self._q_score(kq[1]))
            for k, _ in open_q[:n_open - MAX_OPEN_QUESTIONS]:
                del self.data["questions"][k]

    def add_belief(self, claim: str, about: str, kind: str, origin: str = "", cond: Optional[dict] = None,
                   status: str = "hunch", confidence: float = 0.3, evidence_run: Optional[int] = None) -> Optional[str]:
        for b in self.data["beliefs"].values():
            if b["claim"] == claim:
                return None
        bid = self._next_id("b")
        self.data["beliefs"][bid] = {"claim": claim, "about": about, "kind": kind, "status": status,
                                     "confidence": round(confidence, 2), "for": [evidence_run] if evidence_run else [],
                                     "against": [], "origin": origin, "cond": cond, "updated": time.time()}
        return bid

    def _topic_counts(self, about: str) -> tuple[int, int]:
        """(chases that produced evidence, chases that could not test the topic) from my own run history."""
        row = (self.data.get("topic_stats") or {}).get(about) or {}
        return int(row.get("tested", 0)), int(row.get("untestable", 0))

    def _testability_factor(self, about: str) -> float:
        """~1.0 for an untested topic, ->0 for one my runs keep failing to test (->2 when always testable)."""
        tested, untestable = self._topic_counts(about)
        return 2.0 * (tested + 1) / (tested + untestable + 2)

    def _q_score(self, q: dict[str, Any]) -> float:
        return (float(q.get("priority", 0.5)) * (0.7 ** int(q.get("times_focused", 0)))
                * self._testability_factor(q.get("about", "")))

    def _chase_history_text(self, q: dict[str, Any]) -> str:
        tested, untestable = self._topic_counts(q.get("about", ""))
        chases = tested + untestable
        if not chases:
            return f"chased {q['times_focused']}x before"
        return f"chased {q['times_focused']}x before; testable in {tested}/{chases} past chases of this topic"

    def open_questions(self, k: int = 8) -> list[tuple[str, dict[str, Any]]]:
        qs = [(qid, q) for qid, q in self.data["questions"].items() if q["status"] != "answered"]
        ranked = sorted(qs, key=lambda kq: -self._q_score(kq[1]))
        selected, deferred = [], []
        kind_counts: dict[str, int] = {}
        for qid, q in ranked:
            kind = q.get("kind", "other")
            max_k = 2 if kind == "boss" else 3
            if kind_counts.get(kind, 0) < max_k:
                kind_counts[kind] = kind_counts.get(kind, 0) + 1
                selected.append((qid, q))
                if len(selected) >= k:
                    return selected
            else:
                deferred.append((qid, q))
        for item in deferred:
            if len(selected) < k:
                selected.append(item)
        return selected

    def top_beliefs(self, k: int = 8) -> list[str]:
        bs = sorted(self.data["beliefs"].values(), key=lambda b: (b["status"] == "refuted", -b["confidence"]))
        return [f"[{b['status']} {b['confidence']:.2f}] {b['claim']}" for b in bs[:k]]

    # ------------------------------------------------------------------ seeding from past experience
    SEED_VERSION = 2

    def seed(self) -> None:
        """Turn already-collected experience into beliefs, and untested things into questions."""
        if int(self.data.get("seed_version", 1 if self.data.get("seeded") else 0)) >= self.SEED_VERSION:
            return
        if self.data.get("seeded"):   # migrate v1: drop untouched seed questions, re-seed with v2 rules
            for k in [k for k, q in self.data["questions"].items()
                      if q.get("origin") in ("seen before the journal", "seen but barely tested") and not q.get("times_focused")]:
                del self.data["questions"][k]
        kb = self.engine.kb
        for key, o in (kb.get("objects") or {}).items():
            if not key.startswith("object:"):
                continue
            if o.get("tried", 0) >= 3 and self.world:
                self.add_belief(self.world.object_line(key), key, "object", origin="experience before the journal",
                                status="supported", confidence=min(0.9, o["tried"] / 10))
            elif not self.has_topic(key):
                self.add_question(f"What happens when I go to the {_pretty(key)}?", key, "object", 0.75,
                                  origin="seen but barely tested")
        for table, verb in (("pickups", "Collecting"), ("kills", "Defeating")):
            for key, obs in (kb.get(table) or {}).items():
                n = int(obs.get("n") or 0)
                if n >= 30 and not self.has_topic(key):
                    avg = {rk: round(v / n, 3) for rk, v in (obs.get("sum") or {}).items() if abs(v / n) > 1e-3}
                    self.add_belief(f"{verb} {_pretty(key)} gives on average {avg} (seen {n}x)", key,
                                    table[:-1], origin="experience before the journal", status="supported",
                                    confidence=min(0.95, n / 200))
        disc = kb.get("discoveries") or {}
        pickups_new = [k for k in disc if k.startswith("pickup:") and not self.has_topic(k)]
        for key in pickups_new:
            self.add_question(f"What does the {_pretty(key)} pickup do for me?", key, "pickup", 0.5, origin="seen before the journal")
        bosses = sorted([k for k in disc if k.startswith("boss:") and not self.has_topic(k)],
                        key=lambda k: -float(disc[k].get("first_seen", 0)))
        for key in bosses[:6]:
            self.add_question(f"How do I beat {_pretty(key)}?", key, "boss", 0.55, origin="seen before the journal")
        self.data["seeded"] = True
        self.data["seed_version"] = self.SEED_VERSION

    # ------------------------------------------------------------------ question generators (observation only)
    def note_meta(self, owned: list[dict[str, Any]], tickets: dict[str, Any]) -> None:
        ms = self.data["meta_seen"]
        if owned:
            before = {o.get("dex") for o in ms.get("owned") or []}
            gained = [o for o in owned if before and o.get("dex") not in before]
            for o in gained:
                ms["partners_gained"].append({"dex": o.get("dex"), "name": o.get("name"), "t": time.time()})
            ms["owned"] = owned
            if gained:
                self.add_belief(f"The gacha gave me new partners: {', '.join(str(o.get('name')) for o in gained)}",
                                "meta:gacha", "meta", origin="owned list grew after pulling", status="supported", confidence=0.8)
        if tickets:
            ms["tickets"] = tickets
        self._untried_meta_questions()

    def note_pull(self) -> None:
        self.data["meta_seen"]["gacha_pulls"] = int(self.data["meta_seen"].get("gacha_pulls", 0)) + 1

    def _used_partner_names(self) -> set[str]:
        return {n for n, p in (self.engine.kb.get("partners") or {}).items() if p.get("runs", 0) > 0}

    def _untried_meta_questions(self) -> None:
        ms = self.data["meta_seen"]
        used = self._used_partner_names()
        focus = (self.data.get("next_plan") or {}).get("focus_question")
        open_p = [(k, q) for k, q in self.data["questions"].items() if q["kind"] == "partner" and q["status"] != "answered"]
        # shortlist: a player looks at a few interesting partners at a time, not all 169
        for k, q in sorted(open_p, key=lambda kq: kq[1].get("times_focused", 0))[:max(0, len(open_p) - 3)]:
            if k != focus and not q.get("times_focused"):
                del self.data["questions"][k]
        n_open = sum(1 for q in self.data["questions"].values() if q["kind"] == "partner" and q["status"] != "answered")
        cands = sorted([o for o in ms.get("owned") or [] if o.get("name") and o["name"] not in used
                        and not self.has_topic(f"partner:{o.get('dex')}")],
                       key=lambda o: (-(o.get("rarity") or 0), -((float(o.get("atk") or 0) * 100) + float(o.get("hp") or 0) + float(o.get("spd") or 0)), random.random()))
        for o in cands[:max(0, 3 - n_open)]:
            self.add_question(f"What is it like to play as {o['name']}?", f"partner:{o.get('dex')}", "partner", 0.8,
                              origin=f"I own it but never played it ({len(cands)} untried partners)")
        t = ms.get("tickets") or {}
        if (int(t.get("t1") or 0) + int(t.get("t10") or 0)) > 0 and int(ms.get("gacha_pulls", 0)) == 0:
            self.add_question("What do I get if I spend my tickets on the gacha?", "meta:gacha", "meta", 0.85,
                              origin="I have tickets and never used them")

    def generate_from_run(self, rec: dict[str, Any], run_no: int) -> list[str]:
        new: list[str] = []

        def add(qid: Optional[str]) -> None:
            if qid:
                new.append(qid)

        # Auto-answer partner question if played this run
        pname = rec.get("partner")
        if pname:
            for qid, q in list(self.data["questions"].items()):
                if q["kind"] == "partner" and q["status"] != "answered":
                    dex_str = q["about"].split(":", 1)[1] if ":" in q["about"] else ""
                    if pname == (self._partner_name(dex_str) or q["about"]):
                        q["status"] = "answered"
                        q["answer"] = self.add_belief(
                            f"Played {pname}: survived {_mmss(float(rec.get('time') or 0))}, Lv{rec.get('level')}, {rec.get('kills', 0)} kills",
                            q["about"], "partner", origin=f"played in run {run_no}", status="supported", confidence=0.8, evidence_run=run_no
                        )

        # Auto-answer boss question if defeated this run
        for bname in (rec.get("bosses_defeated") or []):
            b_clean = str(bname).strip().lower()
            for qid, q in list(self.data["questions"].items()):
                if q["kind"] == "boss" and b_clean in q["ask"].lower() and q["status"] != "answered":
                    q["status"] = "answered"
                    q["answer"] = self.add_belief(
                        f"Defeated {bname} in run {run_no} playing {pname} with {len(rec.get('picks', []))} cards",
                        q["about"], "boss", origin=f"defeated in run {run_no}", status="supported", confidence=0.85, evidence_run=run_no
                    )

        # 1. first sightings of map objects / pickups / bosses (a few at a time, most tangible first)
        order = {"object": 0, "pickup": 1, "boss": 2}
        novel = sorted({k for k in (rec.get("world_deltas") or {}).get("seen") or []
                        if k.startswith(NOVEL_PREFIXES) and not self.has_topic(k)}, key=lambda k: order[k.split(":")[0]])
        n_open_boss = sum(1 for q in self.data["questions"].values() if q["kind"] == "boss" and q["status"] != "answered")
        for key in novel[:3]:
            kind = key.split(":")[0]
            if kind == "boss" and n_open_boss >= 3:
                continue
            ask = {"object": f"What happens when I go to the {_pretty(key)}?",
                   "pickup": f"What does the {_pretty(key)} pickup do for me?",
                   "boss": f"How do I beat {_pretty(key)}?"}[kind]
            add(self.add_question(ask, key, kind, 0.7, origin=f"first noticed in run {run_no}"))
            if kind == "boss":
                n_open_boss += 1
        # 2. on-screen text I have never read before
        seen = self.data["seen_messages"]
        n_msg = 0
        for m in rec.get("messages") or []:
            text = str(m.get("text") if isinstance(m, dict) else m).strip()
            norm = re.sub(r"\d+", "#", text.lower())[:80]
            if not text or norm in seen:
                continue
            seen.append(norm)
            if n_msg < 2:
                n_msg += 1
                add(self.add_question(f"The screen said \"{text[:70]}\". What does it mean for me?", f"msg:{norm}",
                                      "message", 0.55, origin=f"read in run {run_no}"))
        self.data["seen_messages"] = seen[-200:]
        # 3. surprise: a special (evolution) card offered for the first time -> hunches about why
        new += self._card_surprises(rec, run_no)
        # 4. the thing hurting me most, if I have no plan for it
        dmg = rec.get("damage_sources") or {}
        if dmg:
            top = max(dmg, key=lambda k: dmg[k])
            if top not in ("unknown",) and not self.has_topic(f"cause:{top}"):
                add(self.add_question(f"How do I stop {_pretty(top)} from hurting me so much?", f"cause:{top}", "cause", 0.6,
                                      origin=f"hurt me most in run {run_no}", candidates=list(STANCES)))
        # 5. dying to the same thing again and again
        runs = self.engine.kb.get("runs", [])[-6:]
        causes = [r.get("cause") for r in runs] + [rec.get("death_cause")]
        if causes:
            c = max(set(causes), key=causes.count)
            if c and causes.count(c) >= 3:
                q = next((q for q in self.data["questions"].values() if q["about"] == f"cause:{c}"), None)
                if q:
                    q["priority"] = round(min(0.95, q["priority"] + 0.1), 2)
                    if q["status"] == "answered":
                        q["status"], q["origin"] = "open", f"still dying to it ({causes.count(c)} of last {len(causes)} runs)"
                else:
                    add(self.add_question(f"How do I stop dying to {_pretty(c)}?", f"cause:{c}", "cause", 0.8,
                                          origin=f"{causes.count(c)} of my last {len(causes)} runs", candidates=list(STANCES)))
        self._untried_meta_questions()
        return new

    @staticmethod
    def _norm_card_key(k: str) -> str:
        if k in ("evo:power", "evo:power-upgrade"):
            return "stat:power"
        if k in ("evo:sprint", "evo:sprint-upgrade"):
            return "stat:sprint"
        if k in ("evo:armor", "evo:armor-upgrade"):
            return "stat:armor"
        return k

    def _is_special(self, key: str) -> bool:
        k = self._norm_card_key(key)
        return k.startswith("evo:") and k not in ("evo:power", "evo:sprint", "evo:armor")

    def _card_surprises(self, rec: dict[str, Any], run_no: int) -> list[str]:
        new: list[str] = []
        for p in rec.get("picks") or []:
            for off in p.get("offered") or []:
                if self._is_special(off) and not self.has_topic(f"card:{off}"):
                    qid = self.add_question(f"What makes '{_pretty(off)}' show up in my level-up choices?", f"card:{off}",
                                            "card", 0.9, origin=f"surprise in run {run_no}")
                    if qid:
                        new.append(qid)
        return new

    # ------------------------------------------------------------------ learning card rules from ALL my runs
    def _counts_before(self, picks: list[dict[str, Any]], card: str) -> tuple[dict[str, int], bool]:
        c: dict[str, int] = {}
        for p in picks:
            offered = [self._norm_card_key(o) for o in (p.get("offered") or [])]
            if card in offered:
                return c, True
            k = self._norm_card_key(p.get("key") or "")
            if k:
                c[k] = c.get(k, 0) + 1
        return c, False

    def mine_card_rules(self, extra: Optional[dict[str, Any]] = None) -> list[dict[str, Any]]:
        """Compare runs where a special card showed up with runs where it didn't: which of MY picks came first?
        necessary = share of 'it showed up' runs where the condition was met before it showed up
        reliable  = P(it shows up | condition met)."""
        runs = [r for r in self._recent_run_files(10_000) if r.get("picks")]
        if extra and extra.get("picks") and not any(r.get("run_id") == extra.get("run_id") for r in runs):
            runs.append(extra)
        specials = {self._norm_card_key(o) for r in runs for p in r["picks"] for o in p.get("offered") or [] if self._is_special(o)}
        rules = []
        for card in sorted(specials):
            rows = [self._counts_before(r["picks"], card) for r in runs]
            pos = [c for c, off in rows if off]
            neg = [c for c, off in rows if not off]
            if len(pos) < 1:
                continue
            best = None
            for k in {k for c in pos for k in c if k != card and k.startswith("up:")}:
                for n in sorted({c[k] for c in pos if c.get(k, 0) >= 3}):
                    met = [c for c in pos + neg if c.get(k, 0) >= n]
                    if not met:
                        continue
                    nec = sum(1 for c in pos if c.get(k, 0) >= n) / len(pos)
                    rel = sum(1 for c in met if any(c is p for p in pos)) / len(met)
                    score = nec * (rel ** 0.5)
                    if not best or score > best["score"]:
                        best = {"card": card, "after": k, "n": n, "necessary": round(nec, 2), "reliable": round(rel, 2),
                                "met_runs": len(met), "shown_runs": len(pos), "score": round(score, 3)}
            if best:
                best_pair = None
                base_k = best["after"]
                base_n = best["n"]
                base_move = base_k.split(":", 1)[1] if ":" in base_k else base_k
                stat_cands = []
                for k2 in {k for c in pos for k in c if k.startswith("stat:") and k != base_k and k != f"new:{base_move}"}:
                    met2 = [c for c in pos + neg if c.get(base_k, 0) >= base_n and c.get(k2, 0) >= 1]
                    if not met2 or len(met2) < len(pos) * 0.5:
                        continue
                    nec2 = sum(1 for c in pos if c.get(base_k, 0) >= base_n and c.get(k2, 0) >= 1) / len(pos)
                    rel2 = sum(1 for c in met2 if any(c is p for p in pos)) / len(met2)
                    score2 = nec2 * (rel2 ** 0.5)
                    stat_cands.append((score2, nec2, rel2, len(met2), k2))
                stat_cands.sort(reverse=True)
                if stat_cands:
                    score2, nec2, rel2, met2_n, k2 = stat_cands[0]
                    second_score = stat_cands[1][0] if len(stat_cands) > 1 else 0.0
                    clearly_distinct = (score2 - second_score) >= 0.12 or len(stat_cands) == 1
                    if clearly_distinct and (rel2 > best["reliable"] + 0.04 or (nec2 >= 0.90 and rel2 >= 0.75 and len(pos) >= 3)):
                        best_pair = {"card": card, "after": base_k, "n": base_n, "paired_with": k2, "n2": 1,
                                     "necessary": round(nec2, 2), "reliable": round(rel2, 2),
                                     "met_runs": met2_n, "shown_runs": len(pos), "score": round(score2, 3)}
                rules.append(best_pair if best_pair else best)
        self._apply_card_rules(rules)
        return rules

    def _apply_card_rules(self, rules: list[dict[str, Any]]) -> None:
        # drop old naive guesses or obsolete special cards (e.g. misclassified stats)
        valid_specials = {r["card"] for r in rules}
        for k, b in list(self.data["beliefs"].items()):
            if b["kind"] == "card" and b.get("cond"):
                c = b["cond"]
                if "mined" not in c or not self._is_special(c.get("card", "")) or c.get("card") not in valid_specials:
                    del self.data["beliefs"][k]
        for qid in [qid for qid, q in self.data["questions"].items() if q["kind"] == "card" and not self._is_special(q["about"].replace("card:", ""))]:
            del self.data["questions"][qid]
        for r in rules:
            about = f"card:{r['card']}"
            strong = r["shown_runs"] >= 3 and r["necessary"] >= 0.85 and r["reliable"] >= 0.50 and r["met_runs"] >= 4
            status = "supported" if strong else "testing"
            verb = "shows up" if strong else "might show up"
            paired = r.get("paired_with")
            paired_txt = f" and pick '{_pretty(paired)}'" if paired else ""
            claim = (f"'{_pretty(r['card'])}' {verb} after I upgrade/pick '{_pretty(r['after'])}' {r['n']}x{paired_txt} "
                     f"(it came after that in {r['necessary']:.0%} of the {r['shown_runs']} runs it appeared; "
                     f"when I did that it appeared {r['reliable']:.0%} of {r['met_runs']} runs)")
            existing = next((b for b in self.data["beliefs"].values() if b["kind"] == "card" and b["about"] == about
                             and (b.get("cond") or {}).get("mined")), None)
            cond = {"mined": True, "card": r["card"], "after": r["after"], "n": r["n"]}
            if paired:
                cond["paired_with"] = paired
                cond["n2"] = r.get("n2", 1)
            conf = 0.90 if strong else round(0.50 + 0.15 * min(2, r["shown_runs"]), 2)
            if existing:
                existing.update({"claim": claim, "status": status, "confidence": conf, "cond": cond, "updated": time.time()})
                bid = next(k for k, b in self.data["beliefs"].items() if b is existing)
            else:
                bid = self.add_belief(claim, about, "card", origin="compared all my runs", cond=cond, status=status,
                                      confidence=conf)
            q = next((q for q in self.data["questions"].values() if q["about"] == about), None)
            if q and strong and q["status"] != "answered":
                q["status"], q["answer"] = "answered", bid

    def card_rules(self, only_supported: bool = False) -> list[dict[str, Any]]:
        return [b for b in self.data["beliefs"].values() if b["kind"] == "card" and (b.get("cond") or {}).get("mined")
                and (b["status"] == "supported" or not only_supported)]

    # ------------------------------------------------------------------ testing hunches with new evidence
    @staticmethod
    def _rescore(b: dict[str, Any]) -> None:
        f, a = len(b["for"]), len(b["against"])
        b["confidence"] = round((f + 0.5) / (f + a + 1.5), 2)
        b["status"] = "supported" if (f >= 2 and b["confidence"] >= 0.7) else "refuted" if (a >= 2 and b["confidence"] <= 0.3) else "hunch"
        b["updated"] = time.time()

    def update_card_beliefs(self, rec: dict[str, Any], run_no: int) -> list[str]:
        """'X shows up after I pick Y n times': did this run support or contradict it?"""
        picks = rec.get("picks") or []
        touched = []
        for bid, b in self.data["beliefs"].items():
            c = b.get("cond")
            if not c or c.get("mined") or b["kind"] != "card" or run_no in b["for"] or run_no in b["against"]:
                continue
            cnt, met_at = 0, None
            for i, p in enumerate(picks):
                if p.get("key") == c["after"]:
                    cnt += 1
                    if cnt >= c["n"] and met_at is None:
                        met_at = i
            if met_at is None:
                continue
            later = picks[met_at + 1:]
            if any(c["card"] in (p.get("offered") or []) for p in later):
                b["for"].append(run_no)
            elif len(later) >= 3:
                b["against"].append(run_no)
            else:
                continue
            self._rescore(b)
            touched.append(bid)
        return touched

