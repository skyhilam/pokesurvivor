    def _apply_focus_verdict(self, qid: str, q: dict[str, Any], verdict: str, ev: list[str], run_no: int) -> None:
        summary = "; ".join(ev[:2]) or "see diary"
        if verdict == "answered" and q["kind"] in ("cause", "boss"):
            key = q["about"].split(":", 1)[1] if q["kind"] == "cause" else q["about"]
            table = {s: v for s, v in (self.data.get("cause_stance", {}).get(key) or {}).items() if v[0] >= 2}
            if len(table) < 2:
                verdict = "keep_investigating"   # one run is not enough to know which play style helps
            else:
                best = min(table, key=lambda s: table[s][1] / table[s][0])
                summary = (f"{STANCES.get(best, {}).get('label', best)} keeps it lowest "
                           f"({table[best][1] / table[best][0]:.0%} of my damage) vs "
                           + ", ".join(f"{STANCES.get(s, {}).get('label', s)} {v[1] / v[0]:.0%}" for s, v in table.items() if s != best))
        if verdict == "answered":
            q["status"] = "answered"
            bid = self.add_belief(f"{q['ask']} -> {summary}", q["about"], q["kind"], origin=f"answered in run {run_no}",
                                  status="supported", confidence=0.7, evidence_run=run_no)
            q["answer"] = bid
        elif verdict == "could_not_test":
            q["status"] = "open"
            q["priority"] = round(max(0.2, q["priority"] * 0.9), 2)
        else:
            q["status"] = "open"
        # remember per topic (survives question trim/regeneration): was this chase testable at all?
        bucket = "untestable" if verdict == "could_not_test" else "tested"
        row = self.data.setdefault("topic_stats", {}).setdefault(q["about"], {"tested": 0, "untestable": 0})
        row[bucket] = int(row.get(bucket, 0)) + 1
        return verdict

